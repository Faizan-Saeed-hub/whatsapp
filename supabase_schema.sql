-- 1. Create Profiles Table
CREATE TABLE IF NOT EXISTS public.profiles (
    email TEXT PRIMARY KEY,
    username TEXT NOT NULL,
    user_tag TEXT NOT NULL UNIQUE,
    about TEXT DEFAULT 'Hey there! I am using WhatsApp.',
    avatar_num TEXT DEFAULT '1',
    avatar_url TEXT,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. Create Groups Table (Supports Group Chats & 1-on-1 Direct Chats)
CREATE TABLE IF NOT EXISTS public.groups (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    description TEXT,
    created_by TEXT,
    is_direct BOOLEAN DEFAULT FALSE,
    participant1 TEXT,
    participant2 TEXT,
    is_pinned BOOLEAN DEFAULT FALSE,
    members TEXT[] DEFAULT '{}',
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Create Messages Table (Supports Text, Media, Replies, Reactions, Seen Ticks, Deletions)
CREATE TABLE IF NOT EXISTS public.messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id BIGINT REFERENCES public.groups(id) ON DELETE CASCADE,
    content TEXT,
    email TEXT NOT NULL,
    media_type TEXT DEFAULT 'text',     -- 'text' | 'image' | 'audio' | 'file'
    media_url TEXT,
    file_name TEXT,
    file_size TEXT,
    reply_to JSONB,                     -- { id, sender, text, media_type }
    reactions JSONB DEFAULT '{}'::jsonb,-- { "❤️": ["user@test.com"], "👍": ["other@test.com"] }
    seen_by TEXT[] DEFAULT '{}',        -- Array of user emails who read the message
    seen_at TIMESTAMPTZ,
    is_deleted BOOLEAN DEFAULT FALSE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. Alter columns to ensure they exist on pre-existing tables
DO $$ 
BEGIN
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='groups' AND column_name='is_direct') THEN
        ALTER TABLE public.groups ADD COLUMN is_direct BOOLEAN DEFAULT FALSE;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='groups' AND column_name='participant1') THEN
        ALTER TABLE public.groups ADD COLUMN participant1 TEXT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='groups' AND column_name='participant2') THEN
        ALTER TABLE public.groups ADD COLUMN participant2 TEXT;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='groups' AND column_name='members') THEN
        ALTER TABLE public.groups ADD COLUMN members TEXT[] DEFAULT '{}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='groups' AND column_name='is_pinned') THEN
        ALTER TABLE public.groups ADD COLUMN is_pinned BOOLEAN DEFAULT FALSE;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='messages' AND column_name='reply_to') THEN
        ALTER TABLE public.messages ADD COLUMN reply_to JSONB;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='messages' AND column_name='reactions') THEN
        ALTER TABLE public.messages ADD COLUMN reactions JSONB DEFAULT '{}'::jsonb;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='messages' AND column_name='seen_by') THEN
        ALTER TABLE public.messages ADD COLUMN seen_by TEXT[] DEFAULT '{}';
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='messages' AND column_name='seen_at') THEN
        ALTER TABLE public.messages ADD COLUMN seen_at TIMESTAMPTZ;
    END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_name='messages' AND column_name='is_deleted') THEN
        ALTER TABLE public.messages ADD COLUMN is_deleted BOOLEAN DEFAULT FALSE;
    END IF;
END $$;

-- 5. Enable REPLICA IDENTITY FULL for complete Realtime replication
ALTER TABLE public.messages REPLICA IDENTITY FULL;
ALTER TABLE public.groups REPLICA IDENTITY FULL;
ALTER TABLE public.profiles REPLICA IDENTITY FULL;

-- 6. Enable Row Level Security (RLS)
ALTER TABLE public.profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.messages ENABLE ROW LEVEL SECURITY;

-- 7. Configure Open Community RLS Policies
DROP POLICY IF EXISTS "Allow select on profiles" ON public.profiles;
CREATE POLICY "Allow select on profiles" ON public.profiles FOR SELECT USING (true);
DROP POLICY IF EXISTS "Allow insert on profiles" ON public.profiles;
CREATE POLICY "Allow insert on profiles" ON public.profiles FOR INSERT WITH CHECK (true);
DROP POLICY IF EXISTS "Allow update on profiles" ON public.profiles;
CREATE POLICY "Allow update on profiles" ON public.profiles FOR UPDATE USING (true);

DROP POLICY IF EXISTS "Allow select on groups" ON public.groups;
CREATE POLICY "Allow select on groups" ON public.groups FOR SELECT USING (true);
DROP POLICY IF EXISTS "Allow insert on groups" ON public.groups;
CREATE POLICY "Allow insert on groups" ON public.groups FOR INSERT WITH CHECK (true);
DROP POLICY IF EXISTS "Allow update on groups" ON public.groups;
CREATE POLICY "Allow update on groups" ON public.groups FOR UPDATE USING (true);
DROP POLICY IF EXISTS "Allow delete on groups" ON public.groups;
CREATE POLICY "Allow delete on groups" ON public.groups FOR DELETE USING (true);

DROP POLICY IF EXISTS "Allow select on messages" ON public.messages;
CREATE POLICY "Allow select on messages" ON public.messages FOR SELECT USING (true);
DROP POLICY IF EXISTS "Allow insert on messages" ON public.messages;
CREATE POLICY "Allow insert on messages" ON public.messages FOR INSERT WITH CHECK (true);
DROP POLICY IF EXISTS "Allow update on messages" ON public.messages;
CREATE POLICY "Allow update on messages" ON public.messages FOR UPDATE USING (true);
DROP POLICY IF EXISTS "Allow delete on messages" ON public.messages;
CREATE POLICY "Allow delete on messages" ON public.messages FOR DELETE USING (true);

-- 8. Enable Realtime Publications (Idempotent - will not error if already added)
DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
        AND schemaname = 'public' 
        AND tablename = 'profiles'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.profiles;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
        AND schemaname = 'public' 
        AND tablename = 'groups'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.groups;
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_publication_tables 
        WHERE pubname = 'supabase_realtime' 
        AND schemaname = 'public' 
        AND tablename = 'messages'
    ) THEN
        ALTER PUBLICATION supabase_realtime ADD TABLE public.messages;
    END IF;
END $$;

